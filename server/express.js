// Import Express and backend middleware.
import express from "express";
import cookieParser from "cookie-parser";
import compress from "compression";
import cors from "cors";
import helmet from "helmet";

// Import the Portfolio REST API routes.
import authRoutes from "./routes/auth.routes.js";
import contactRoutes from "./routes/contact.routes.js";
import educationRoutes from "./routes/education.routes.js";
import projectRoutes from "./routes/project.routes.js";
import userRoutes from "./routes/user.routes.js";

const app = express();

// Configure middleware before mounting API routes.
app.use(cors());
app.use(helmet());
app.use(compress());
app.use(cookieParser());
app.use(express.json());
app.use(express.urlencoded({ extended: true }));

// Mount the Portfolio REST API routes.
app.use("/", authRoutes);
app.use("/", contactRoutes);
app.use("/", educationRoutes);
app.use("/", projectRoutes);
app.use("/", userRoutes);

// Handle authentication errors generated by express-jwt.
app.use((err, req, res, next) => {
  if (err.name === "UnauthorizedError") {
    return res.status(401).json({
      error: `${err.name}: ${err.message}`,
    });
  }

  if (err) {
    console.log(err);

    return res.status(400).json({
      error: `${err.name}: ${err.message}`,
    });
  }

  next();
});

export default app;